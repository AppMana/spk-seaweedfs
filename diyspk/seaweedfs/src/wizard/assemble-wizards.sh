#!/bin/sh
# Builds install_uifile.sh and upgrade_uifile.sh: each wizard's static steps
# (a JSON array) followed by the "Volume servers" step servers-step.sh prints
# on the NAS. DSM runs these scripts and reads the wizard from
# $SYNOPKG_TEMP_LOGFILE. Usage: assemble-wizards.sh <this dir> <output dir>
set -eu
src=$1
out=$2
mkdir -p "$out"
for wizard in install upgrade; do
    steps="$src/$wizard-steps.json"
    # the static steps without the array's own brackets
    python3 -c 'import json, sys; s = json.load(open(sys.argv[1])); print(",\n".join(json.dumps(x, indent=3) for x in s))' "$steps" > "$out/.steps"
    {
        echo '#!/bin/sh'
        echo "# Generated by assemble-wizards.sh from $wizard-steps.json and servers-step.sh."
        cat "$src/servers-step.sh"
        echo 'steps=$(cat <<'"'"'STEPS'"'"''
        cat "$out/.steps"
        echo 'STEPS'
        echo ')'
        echo '{ printf "[%s,\n" "$steps"; servers_step; printf "]\n"; } > "${SYNOPKG_TEMP_LOGFILE}"'
    } > "$out/${wizard}_uifile.sh"
    chmod 755 "$out/${wizard}_uifile.sh"
    rm -f "$out/.steps"
done
